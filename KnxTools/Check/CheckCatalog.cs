        public static string AsText()
        {
            var sb = new StringBuilder();
            sb.AppendLine("===== Проверки проекта: SDK_CHECK_PROJECT =====");
            foreach (var c in All)
            {
                sb.AppendLine($"{c.Id}  [{c.LevelText}]  {c.Title}   ({c.Source})");
                sb.AppendLine($"      что:    {c.What}");
                sb.AppendLine($"      делать: {c.Action}");
                if (c.Skip != "—") sb.AppendLine($"      флаг:   {c.Skip}");
            }
            sb.AppendLine("===== Флаг «НЕТ» и соглашения =====");
            foreach (var r in NoneRules) sb.AppendLine("  " + r);
            return sb.ToString();
        }
