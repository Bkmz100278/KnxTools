using System.Text;

namespace KnxTools.Check
{
    public enum CheckLevel { Fatal = 0, Error = 1, Notice = 2 }

    public sealed class CheckCode
    {
        public readonly string Id;
        public readonly CheckLevel Level;
        public readonly string Source, Title, What, Action, Skip;

        public CheckCode(string id, CheckLevel level, string source, string title, string what, string action, string skip)
        { Id = id; Level = level; Source = source; Title = title; What = what; Action = action; Skip = skip; }

        public string LevelText
        {
            get
            {
                switch (Level)
                {
                    case CheckLevel.Fatal: return "ФАТАЛЬНО — проверка невозможна";
                    case CheckLevel.Error: return "ОШИБКА — исправить";
                    default: return "ВНИМАНИЕ — обратить внимание";
                }
            }
        }
    }

